//! Note-altering devices (rack section NOTE FX): Chord, Arp, Note Repeat.
//!
//! They turn the block's note events into new ones. Timed devices (Arp, Note Repeat) step on
//! a beat grid: the song position while the transport runs, an internal clock while it is
//! stopped. Note-offs that fall into later blocks are kept as sample countdowns, so they
//! survive transport jumps. No allocation: all state lives in fixed arrays.

use super::{ParamDef, Unit};
use crate::engine::sequencer::sort_events;
use crate::engine::NoteEvent;

/// Per-block context for note processors.
pub struct NoteCtx {
    pub sample_rate: f32,
    pub bpm: f64,
    pub frames: u32,
    /// Song position (beats) at the block start, if the transport is running.
    pub song_beat: Option<f64>,
}

pub trait NoteDsp: Send {
    /// Reads `input` (sorted by time) and writes the replacement events into `out` (empty on
    /// entry, enough capacity). The caller sorts `out` afterwards.
    fn process(&mut self, p: &[f32], input: &[NoteEvent], out: &mut Vec<NoteEvent>, ctx: &NoteCtx);
}

fn push(out: &mut Vec<NoteEvent>, time: u32, on: bool, key: u8, velocity: f32) {
    if out.len() < out.capacity() {
        out.push(NoteEvent { time, on, key, velocity });
    }
}

const RATES: &[&str] = &["1/4", "1/8", "1/8T", "1/16", "1/16T", "1/32"];
const RATE_BEATS: [f64; 6] = [1.0, 0.5, 1.0 / 3.0, 0.25, 1.0 / 6.0, 0.125];
const OFF_ON: &[&str] = &["Off", "On"];

fn rate_beats(p: f32) -> f64 {
    RATE_BEATS[(p as usize).min(RATE_BEATS.len() - 1)]
}

/// Beat grid shared by the timed devices.
struct Clock {
    /// Internal position while the transport is stopped.
    free_beat: f64,
}

impl Clock {
    fn new() -> Self {
        Self { free_beat: 0.0 }
    }

    /// Calls `f(frame)` for every grid point of `step` beats inside this block, then advances.
    fn steps(&mut self, ctx: &NoteCtx, step: f64, mut f: impl FnMut(u32)) {
        let beats_per_frame = ctx.bpm / 60.0 / ctx.sample_rate as f64;
        let start = ctx.song_beat.unwrap_or(self.free_beat);
        let end = start + ctx.frames as f64 * beats_per_frame;
        let mut k = (start / step - 1e-9).ceil();
        while k * step < end {
            let frame = ((k * step - start) / beats_per_frame).round().max(0.0) as u32;
            if frame < ctx.frames {
                f(frame);
            }
            k += 1.0;
        }
        self.free_beat = end;
    }
}

fn samples_per_beat(ctx: &NoteCtx) -> f64 {
    ctx.sample_rate as f64 * 60.0 / ctx.bpm.max(1.0)
}

// ---------------------------------------------------------------- chord

const CHORDS: &[&str] = &["Major", "Minor", "Sus2", "Sus4", "7", "Maj7", "Min7", "Dim", "Aug", "Power", "Octave"];
const CHORD_INTERVALS: [&[i8]; 11] = [
    &[0, 4, 7],
    &[0, 3, 7],
    &[0, 2, 7],
    &[0, 5, 7],
    &[0, 4, 7, 10],
    &[0, 4, 7, 11],
    &[0, 3, 7, 10],
    &[0, 3, 6],
    &[0, 4, 8],
    &[0, 7],
    &[0, 12],
];
const INVERSIONS: &[&str] = &["Root", "1st", "2nd", "3rd"];
const OCTAVES: &[&str] = &["-2", "-1", "0", "+1", "+2"];

pub const CHORD_PARAMS: &[ParamDef] = &[
    ParamDef::choice("type", "Chord", CHORDS, 0),
    ParamDef::choice("inversion", "Inversion", INVERSIONS, 0),
    ParamDef::choice("octave", "Octave", OCTAVES, 2),
    ParamDef::new("strum", "Strum", 0.0, 100.0, 0.0, Unit::Ms).linear(),
];

const MAX_CHORD: usize = 4;

/// Plays a chord for every incoming note. Output keys are reference counted, so chords that
/// share a note do not cut each other off.
pub struct Chord {
    /// Output keys generated by each input key.
    map: [[u8; MAX_CHORD]; 128],
    map_len: [u8; 128],
    count: [u8; 128],
    /// Strummed note-ons still to come: (samples left, key, velocity, source key).
    pending: [(u32, u8, f32, u8); 64],
    pending_len: usize,
}

impl Default for Chord {
    fn default() -> Self {
        Self {
            map: [[0; MAX_CHORD]; 128],
            map_len: [0; 128],
            count: [0; 128],
            pending: [(0, 0, 0.0, 0); 64],
            pending_len: 0,
        }
    }
}

impl Chord {
    fn note_on(&mut self, out: &mut Vec<NoteEvent>, time: u32, key: u8, velocity: f32) {
        if self.count[key as usize] == 0 {
            push(out, time, true, key, velocity);
        }
        self.count[key as usize] = self.count[key as usize].saturating_add(1);
    }

    fn note_off(&mut self, out: &mut Vec<NoteEvent>, time: u32, key: u8) {
        let c = &mut self.count[key as usize];
        if *c > 0 {
            *c -= 1;
            if *c == 0 {
                push(out, time, false, key, 0.0);
            }
        }
    }

    /// Releases the chord of `src`: pending strums are dropped, sounding notes end.
    fn release(&mut self, out: &mut Vec<NoteEvent>, time: u32, src: u8) {
        let s = src as usize;
        let mut i = 0;
        while i < self.pending_len {
            if self.pending[i].3 == src {
                self.pending[i] = self.pending[self.pending_len - 1];
                self.pending_len -= 1;
            } else {
                i += 1;
            }
        }
        for j in 0..self.map_len[s] as usize {
            let k = self.map[s][j];
            // Strummed notes that never started have no count to release.
            if self.count[k as usize] > 0 {
                self.note_off(out, time, k);
            }
        }
        self.map_len[s] = 0;
    }
}

impl NoteDsp for Chord {
    fn process(&mut self, p: &[f32], input: &[NoteEvent], out: &mut Vec<NoteEvent>, ctx: &NoteCtx) {
        // Strummed notes due in this block.
        let mut i = 0;
        while i < self.pending_len {
            let (left, key, vel, _) = self.pending[i];
            if left < ctx.frames {
                self.note_on(out, left, key, vel);
                self.pending[i] = self.pending[self.pending_len - 1];
                self.pending_len -= 1;
            } else {
                self.pending[i].0 -= ctx.frames;
                i += 1;
            }
        }
        let intervals = CHORD_INTERVALS[(p[0] as usize).min(CHORD_INTERVALS.len() - 1)];
        let inversion = p[1] as usize;
        let octave = (p[2] as i32 - 2) * 12;
        let strum = (p[3] * 0.001 * ctx.sample_rate) as u32;
        for e in input {
            let src = e.key;
            if !e.on {
                self.release(out, e.time, src);
                continue;
            }
            self.release(out, e.time, src);
            // Build the voicing: the lowest `inversion` notes move up an octave.
            let mut keys = [0i32; MAX_CHORD];
            let n = intervals.len().min(MAX_CHORD);
            for (j, iv) in intervals.iter().take(n).enumerate() {
                keys[j] = src as i32 + *iv as i32 + octave + if j < inversion.min(n - 1) { 12 } else { 0 };
            }
            keys[..n].sort_unstable();
            let s = src as usize;
            self.map_len[s] = 0;
            for (j, &k) in keys[..n].iter().enumerate() {
                if !(0..128).contains(&k) {
                    continue;
                }
                let k = k as u8;
                self.map[s][self.map_len[s] as usize] = k;
                self.map_len[s] += 1;
                let at = e.time as u64 + strum as u64 * j as u64;
                if at < ctx.frames as u64 {
                    self.note_on(out, at as u32, k, e.velocity);
                } else if self.pending_len < self.pending.len() {
                    self.pending[self.pending_len] = (at as u32 - ctx.frames, k, e.velocity, src);
                    self.pending_len += 1;
                }
            }
        }
    }
}

// ---------------------------------------------------------------- arpeggiator

const ARP_MODES: &[&str] = &["Up", "Down", "Up-Down", "Down-Up", "Random", "As Played"];
const ARP_OCTAVES: &[&str] = &["1", "2", "3", "4"];

pub const ARP_PARAMS: &[ParamDef] = &[
    ParamDef::choice("mode", "Mode", ARP_MODES, 0),
    ParamDef::choice("rate", "Rate", RATES, 3),
    ParamDef::new("gate", "Gate", 0.05, 1.0, 0.6, Unit::Percent),
    ParamDef::choice("octaves", "Octaves", ARP_OCTAVES, 0),
    ParamDef::choice("latch", "Latch", OFF_ON, 0),
];

const MAX_HELD: usize = 32;

pub struct Arp {
    /// Held keys in the order they were pressed, with their velocity.
    held: [(u8, f32); MAX_HELD],
    held_len: usize,
    /// Number of physically held keys (differs from `held_len` while latched).
    down: usize,
    step: usize,
    sounding: Option<u8>,
    /// Samples until the sounding note ends.
    off_in: u32,
    clock: Clock,
    rng: u32,
}

impl Default for Arp {
    fn default() -> Self {
        Self {
            held: [(0, 0.0); MAX_HELD],
            held_len: 0,
            down: 0,
            step: 0,
            sounding: None,
            off_in: 0,
            clock: Clock::new(),
            rng: 0x9e37_79b9,
        }
    }
}

impl Arp {
    /// The key and velocity of step `step` for the current held notes.
    fn pick(&mut self, mode: usize, octaves: usize) -> Option<(u8, f32)> {
        let n = self.held_len;
        if n == 0 {
            return None;
        }
        let mut sorted = [(0u8, 0f32); MAX_HELD];
        sorted[..n].copy_from_slice(&self.held[..n]);
        if mode != 5 {
            sorted[..n].sort_unstable_by_key(|h| h.0);
        }
        let total = n * octaves;
        let at = |i: usize| -> (u8, f32) {
            let (k, v) = sorted[i % n];
            ((k as usize + 12 * (i / n)).min(127) as u8, v)
        };
        let s = self.step;
        let idx = match mode {
            1 => total - 1 - s % total,
            2 | 3 => {
                // Ping-pong without repeating the turning notes.
                let period = (2 * total).saturating_sub(2).max(1);
                let m = s % period;
                let up = if m < total { m } else { period - m };
                if mode == 2 { up } else { total - 1 - up }
            }
            4 => {
                self.rng ^= self.rng << 13;
                self.rng ^= self.rng >> 17;
                self.rng ^= self.rng << 5;
                self.rng as usize % total
            }
            _ => s % total,
        };
        self.step = self.step.wrapping_add(1);
        Some(at(idx))
    }

    fn stop(&mut self, out: &mut Vec<NoteEvent>, time: u32) {
        if let Some(k) = self.sounding.take() {
            push(out, time, false, k, 0.0);
        }
    }

    fn trigger(&mut self, out: &mut Vec<NoteEvent>, time: u32, p: &[f32], ctx: &NoteCtx) {
        self.stop(out, time);
        if let Some((k, v)) = self.pick(p[0] as usize, p[3] as usize + 1) {
            push(out, time, true, k, v);
            self.sounding = Some(k);
            let len = rate_beats(p[1]) * p[2] as f64 * samples_per_beat(ctx);
            self.off_in = time + (len as u32).max(1);
        }
    }
}

impl NoteDsp for Arp {
    fn process(&mut self, p: &[f32], input: &[NoteEvent], out: &mut Vec<NoteEvent>, ctx: &NoteCtx) {
        let latch = p[4] >= 0.5;
        // Gate end of the note started in an earlier block.
        if self.sounding.is_some() && self.off_in < ctx.frames {
            self.stop(out, self.off_in);
        }
        let mut idle = self.held_len == 0;
        for e in input {
            if e.on {
                // Latched: a new chord replaces the old one once all keys were released.
                if latch && self.down == 0 {
                    self.held_len = 0;
                }
                self.down += 1;
                if let Some(h) = self.held[..self.held_len].iter_mut().find(|h| h.0 == e.key) {
                    h.1 = e.velocity;
                } else if self.held_len < MAX_HELD {
                    self.held[self.held_len] = (e.key, e.velocity);
                    self.held_len += 1;
                }
                if idle {
                    // Start right away instead of waiting for the next grid step.
                    self.step = 0;
                    self.trigger(out, e.time, p, ctx);
                    idle = false;
                }
            } else {
                self.down = self.down.saturating_sub(1);
                if !latch {
                    if let Some(i) = self.held[..self.held_len].iter().position(|h| h.0 == e.key) {
                        self.held.copy_within(i + 1..self.held_len, i);
                        self.held_len -= 1;
                    }
                    if self.held_len == 0 {
                        self.stop(out, e.time);
                        idle = true;
                    }
                }
            }
        }
        if !latch && self.down == 0 && self.held_len > 0 {
            // Latch was switched off while nothing is held.
            self.held_len = 0;
            self.stop(out, 0);
        }
        let step = rate_beats(p[1]);
        let mut grid = [0u32; 64];
        let mut n = 0;
        self.clock.steps(ctx, step, |f| {
            if n < grid.len() {
                grid[n] = f;
                n += 1;
            }
        });
        let first_on = out.iter().filter(|e| e.on).map(|e| e.time).min();
        for &f in &grid[..n] {
            // Skip a grid step that coincides with the immediate start above.
            if self.held_len == 0 || first_on == Some(f) {
                continue;
            }
            if let Some(k) = self.sounding {
                if self.off_in > f {
                    push(out, f, false, k, 0.0);
                    self.sounding = None;
                }
            }
            self.trigger(out, f, p, ctx);
        }
        if self.sounding.is_some() {
            if self.off_in < ctx.frames {
                self.stop(out, self.off_in);
            } else {
                self.off_in -= ctx.frames;
            }
        }
    }
}

// ---------------------------------------------------------------- note repeat

pub const REPEAT_PARAMS: &[ParamDef] = &[
    ParamDef::choice("rate", "Rate", RATES, 3),
    ParamDef::new("gate", "Gate", 0.05, 1.0, 0.5, Unit::Percent),
    ParamDef::new("decay", "Decay", 0.0, 0.9, 0.0, Unit::Percent),
];

/// Retriggers every held key on the beat grid until it is released.
pub struct NoteRepeat {
    /// Velocity of the next repeat for held keys (0 = not held).
    held: [f32; 128],
    /// Samples until the sounding repeat ends (u32::MAX = not sounding).
    off_in: [u32; 128],
    clock: Clock,
}

impl Default for NoteRepeat {
    fn default() -> Self {
        Self {
            held: [0.0; 128],
            off_in: [u32::MAX; 128],
            clock: Clock::new(),
        }
    }
}

impl NoteDsp for NoteRepeat {
    fn process(&mut self, p: &[f32], input: &[NoteEvent], out: &mut Vec<NoteEvent>, ctx: &NoteCtx) {
        let step = rate_beats(p[0]);
        let gate = (step * p[1] as f64 * samples_per_beat(ctx)).max(1.0) as u32;
        let decay = 1.0 - p[2];
        // Collect grid points first; key presses and grid steps are merged in time order.
        let mut grid = [0u32; 64];
        let mut n = 0;
        self.clock.steps(ctx, step, |f| {
            if n < grid.len() {
                grid[n] = f;
                n += 1;
            }
        });
        let mut gi = 0;
        let fire = |this: &mut Self, out: &mut Vec<NoteEvent>, gi: &mut usize, until: u32, inclusive: bool| {
            while *gi < n && (grid[*gi] < until || (inclusive && grid[*gi] == until)) {
                let f = grid[*gi];
                for k in 0..128 {
                    if this.held[k] > 0.0 {
                        if this.off_in[k] != u32::MAX {
                            push(out, f, false, k as u8, 0.0);
                        }
                        push(out, f, true, k as u8, this.held[k]);
                        this.off_in[k] = f + gate;
                        this.held[k] = (this.held[k] * decay).max(0.05);
                    }
                }
                *gi += 1;
            }
        };
        for e in input {
            fire(self, out, &mut gi, e.time, false);
            let k = e.key as usize & 127;
            if e.on {
                if self.off_in[k] != u32::MAX {
                    push(out, e.time, false, e.key, 0.0);
                }
                push(out, e.time, true, e.key, e.velocity);
                self.off_in[k] = e.time + gate;
                self.held[k] = (e.velocity * decay).max(0.05);
            } else {
                self.held[k] = 0.0;
                if self.off_in[k] != u32::MAX {
                    push(out, e.time, false, e.key, 0.0);
                    self.off_in[k] = u32::MAX;
                }
            }
        }
        // Grid steps at the same time as a key press were covered by the press itself.
        let pressed_at = |f: u32| input.iter().any(|e| e.on && e.time == f);
        while gi < n {
            if pressed_at(grid[gi]) {
                gi += 1;
                continue;
            }
            let until = grid[gi];
            fire(self, out, &mut gi, until, true);
        }
        // Gate ends inside this block; the rest count down.
        for k in 0..128 {
            let off = self.off_in[k];
            if off == u32::MAX {
                continue;
            }
            if off < ctx.frames {
                // A retrigger after the gate end restarted the countdown; only end what is due.
                let retriggered = out.iter().any(|e| e.on && e.key == k as u8 && e.time > off);
                if !retriggered {
                    push(out, off, false, k as u8, 0.0);
                    self.off_in[k] = u32::MAX;
                    continue;
                }
            }
            self.off_in[k] = off.saturating_sub(ctx.frames);
        }
        sort_events(out);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const SR: f32 = 48_000.0;
    // 120 bpm: 24 000 samples per beat; 1/16 = 6000 samples.

    fn ev(time: u32, on: bool, key: u8) -> NoteEvent {
        NoteEvent { time, on, key, velocity: 0.8 }
    }

    /// Runs blocks of 1000 frames; `input` maps an absolute frame to events. Returns absolute
    /// (frame, on, key) of the output.
    fn run(dsp: &mut dyn NoteDsp, p: &[f32], input: &[(u64, bool, u8)], blocks: u64, playing: bool) -> Vec<(u64, bool, u8)> {
        let mut all = Vec::new();
        for b in 0..blocks {
            let start = b * 1000;
            let inp: Vec<NoteEvent> = input
                .iter()
                .filter(|e| e.0 >= start && e.0 < start + 1000)
                .map(|e| ev((e.0 - start) as u32, e.1, e.2))
                .collect();
            let mut out = Vec::with_capacity(256);
            let ctx = NoteCtx {
                sample_rate: SR,
                bpm: 120.0,
                frames: 1000,
                song_beat: playing.then_some(start as f64 / 24_000.0),
            };
            dsp.process(p, &inp, &mut out, &ctx);
            sort_events(&mut out);
            all.extend(out.iter().map(|e| (start + e.time as u64, e.on, e.key)));
        }
        all
    }

    #[test]
    fn chord_plays_and_releases_a_triad() {
        let mut c = Chord::default();
        let out = run(&mut c, &[1.0, 0.0, 2.0, 0.0], &[(100, true, 60), (5000, false, 60)], 6, false);
        assert_eq!(
            out,
            vec![(100, true, 60), (100, true, 63), (100, true, 67), (5000, false, 60), (5000, false, 63), (5000, false, 67)]
        );
    }

    #[test]
    fn chord_inversion_and_strum_across_blocks() {
        let mut c = Chord::default();
        // Major, 1st inversion, 10 ms strum (480 samples): E4 G4 C5.
        let out = run(&mut c, &[0.0, 1.0, 2.0, 10.0], &[(900, true, 60), (3000, false, 60)], 4, false);
        assert_eq!(
            out,
            vec![(900, true, 64), (1380, true, 67), (1860, true, 72), (3000, false, 64), (3000, false, 67), (3000, false, 72)]
        );
    }

    #[test]
    fn shared_chord_notes_are_reference_counted() {
        let mut c = Chord::default();
        // C major (C E G) and E "power" ... use Octave chord on 60 and 48: 48 -> 48, 60; 60 -> 60, 72.
        let out = run(&mut c, &[10.0, 0.0, 2.0, 0.0], &[(0, true, 48), (10, true, 60), (20, false, 48), (30, false, 60)], 1, false);
        // 60 starts once and ends only when both chords are released.
        assert_eq!(out, vec![(0, true, 48), (0, true, 60), (10, true, 72), (20, false, 48), (30, false, 60), (30, false, 72)]);
    }

    #[test]
    fn arp_steps_up_on_the_sixteenth_grid() {
        let mut a = Arp::default();
        // Up, 1/16, 50 % gate, 1 octave; chord C E G held from frame 0 to 30 000.
        let p = [0.0, 3.0, 0.5, 0.0, 0.0];
        let input = [(0, true, 60), (0, true, 64), (0, true, 67), (30_000, false, 60), (30_000, false, 64), (30_000, false, 67)];
        let out = run(&mut a, &p, &input, 40, true);
        let ons: Vec<(u64, u8)> = out.iter().filter(|e| e.1).map(|e| (e.0, e.2)).collect();
        assert_eq!(ons, vec![(0, 60), (6000, 64), (12_000, 67), (18_000, 60), (24_000, 64)]);
        // Every on has an off 3000 samples later (50 % of a sixteenth).
        let offs: Vec<u64> = out.iter().filter(|e| !e.1).map(|e| e.0).collect();
        assert_eq!(offs, vec![3000, 9000, 15_000, 21_000, 27_000]);
    }

    #[test]
    fn arp_latch_keeps_playing_after_release() {
        let mut a = Arp::default();
        let p = [0.0, 3.0, 0.5, 0.0, 1.0];
        let out = run(&mut a, &p, &[(0, true, 60), (1000, false, 60)], 20, true);
        assert_eq!(out.iter().filter(|e| e.1).count(), 4); // 0, 6000, 12 000, 18 000
    }

    #[test]
    fn note_repeat_retriggers_until_release() {
        let mut r = NoteRepeat::default();
        // 1/16, 50 % gate; key held 0..20 000 (beats 0 .. 0.83).
        let out = run(&mut r, &[3.0, 0.5, 0.0], &[(0, true, 60), (20_000, false, 60)], 30, true);
        assert_eq!(
            out,
            vec![
                (0, true, 60),
                (3000, false, 60),
                (6000, true, 60),
                (9000, false, 60),
                (12_000, true, 60),
                (15_000, false, 60),
                (18_000, true, 60),
                (20_000, false, 60)
            ]
        );
    }
}
